export type Direction = "up" | "down" | "left" | "right";

// 問1
export function turnRight(direction: Direction): Direction {
  if (direction === "up") {
    return "right";
  }
  if (direction === "right") {
    return "down";
  }
  if (direction === "down") {
    return "left";
  }
  return "up";
}
