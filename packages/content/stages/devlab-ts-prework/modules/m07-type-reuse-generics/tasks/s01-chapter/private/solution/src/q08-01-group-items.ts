// 問1
export function groupItems<T>(
  items: readonly T[],
  keyFn: (item: T) => string,
): Record<string, T[]> {
  const groups: Record<string, T[]> = {};
  for (const item of items) {
    const key = keyFn(item);
    groups[key] = [...(groups[key] ?? []), item];
  }
  return groups;
}
