// 問6
export function chunked<T>(items: readonly T[], size: number): T[][] {
  if (size < 1) {
    throw new Error("size は1以上にしてください");
  }
  const result: T[][] = [];
  for (let i = 0; i < items.length; i += size) {
    result.push(items.slice(i, i + size));
  }
  return result;
}
