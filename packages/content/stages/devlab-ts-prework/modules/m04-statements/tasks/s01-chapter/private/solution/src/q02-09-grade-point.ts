// 問9
export function gradePoint(grade: "A" | "B" | "C" | "D" | "F"): number {
  switch (grade) {
    case "A":
      return 4;
    case "B":
      return 3;
    case "C":
      return 2;
    case "D":
      return 1;
    case "F":
      return 0;
  }
}
