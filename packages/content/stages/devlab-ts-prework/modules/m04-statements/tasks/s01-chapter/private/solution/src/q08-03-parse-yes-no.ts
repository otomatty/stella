// 問3
export function parseYesNo(text: string): boolean {
  switch (text.toLowerCase()) {
    case "true":
    case "yes":
    case "1":
      return true;
    case "false":
    case "no":
    case "0":
      return false;
    default:
      throw new Error(`真偽値ではありません: ${text}`);
  }
}
